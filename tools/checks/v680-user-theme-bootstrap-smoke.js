#!/usr/bin/env node
'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'../..');
const read=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const app=read('server/app.js');
const route=read('server/routes/theme-bootstrap-routes.js');
const login=read('public/scripts/login.js');
const boot=read('public/scripts/theme-boot.js');
const scope=read('public/scripts/rebuild/core/user-scope-bootstrap.mjs');
const api=read('public/scripts/rebuild/core/api.mjs');
const metadata=read('public/scripts/rebuild/metadata-page.mjs');
const appearance=read('public/scripts/rebuild/features/settings/appearance.mjs');
assert(app.includes("require('./routes/theme-bootstrap-routes')"),'theme bootstrap router import missing');
assert(app.includes("app.use('/api', createThemeBootstrapRouter("),'theme bootstrap router mount missing');
assert(route.includes("router.get('/theme-bootstrap'"),'theme bootstrap endpoint missing');
for(const key of ['themeMode','themePresetId','themeColors','readerBg','readerText']) assert(route.includes(`'${key}'`),`theme key missing: ${key}`);
assert(route.includes("session.kind === 'owner'")&&route.includes("session.kind !== 'user'"),'owner/user theme separation missing');
assert(route.includes('getUserStateResponse(req)'),'user theme state source missing');
assert(login.includes("fetch('/api/theme-bootstrap'"),'login theme prime request missing');
assert(login.includes("txt-reader.rebuild.activeThemeScope"),'login active theme scope marker missing');
assert(login.includes("txt-reader.rebuild.scope."),'login scoped theme persistence missing');
assert(boot.includes("PREFIX + 'activeThemeScope'"),'first-paint active scope read missing');
assert(boot.includes("SCOPED_PREFIX + normalized + '.prefs'"),'first-paint scoped prefs read missing');
assert(scope.includes("localStorage.setItem(ACTIVE_THEME_SCOPE_KEY, scope)"),'authenticated scope marker update missing');
assert(api.includes("themeBootstrap(options) { return this.get('/api/theme-bootstrap', options); }"),'api theme bootstrap method missing');
const hydrateAt=metadata.indexOf('await hydrateMetadataPageTheme();');
const createAt=metadata.indexOf("appState = createState({ profile:'library' });");
assert(hydrateAt>=0&&createAt>=0&&hydrateAt>createAt,'metadata startup/hydration markers missing');
const startAt=metadata.indexOf('async function start()');
assert(startAt>=0&&metadata.indexOf('await hydrateMetadataPageTheme();',startAt)>startAt,'metadata must hydrate theme before page startup');
assert(appearance.includes("document.body.dataset.theme = dark ? 'dark' : 'light'"),'body theme runtime sync missing');
assert(appearance.includes('meta[name="theme-color"]'),'theme-color runtime sync missing');
console.log(JSON.stringify({pass:'v680-user-theme-bootstrap-wiring-pass'}));
