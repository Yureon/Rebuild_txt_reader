const fs = require('fs');
const path = require('path');
const assert = require('assert');
const root = path.join(__dirname, '../..');
const PASS = 'v434-reader-api-conditional-cache-smoke-pass';
function read(rel) { return fs.readFileSync(path.join(root, rel), 'utf8'); }
const novels = read('server/routes/novels-routes.js');
const api = read('public/scripts/rebuild/core/api.mjs');
assert.ok(novels.includes("NOVELS_CONDITIONAL_CACHE_PASS = 'v434-novels-conditional-cache-pass'"), 'novels conditional cache marker missing');
assert.ok(novels.includes("CONTENT_CHUNK_CONDITIONAL_CACHE_PASS = 'v434-content-chunk-conditional-cache-pass'"), 'content chunk conditional cache marker missing');
assert.ok(novels.includes('function buildAuthCacheScope'), 'auth cache scope helper missing');
assert.ok(novels.includes('accessVersion'), 'etag scope must include accessVersion');
assert.ok(novels.includes('accessSig'), 'etag scope must include access signature');
assert.ok(novels.includes('librarySignature'), '/api/novels etag must include library signature');
assert.ok(novels.includes('bodyHash'), 'etag must include stable body hash');
assert.ok(novels.includes('fileStatSig'), 'content etag must include file stat signature');
assert.ok(novels.includes('fileTextHash'), 'content etag must include content identity hash');
assert.ok(novels.includes('preprocessSig'), 'content etag must include preprocess signature');
assert.ok(novels.includes("appendVaryHeader(res, 'Cookie')"), 'reader API cache must vary by cookie');
assert.ok(novels.includes("private, max-age=0, must-revalidate"), 'reader API must use private revalidation cache policy');
assert.ok(novels.includes('if-none-match'), 'reader API must handle If-None-Match');
assert.ok(novels.includes('res.status(304).end()'), 'reader API must return empty 304 body');
assert.ok(api.includes('shouldUseReaderRevalidationCache'), 'client cache-mode gate missing');
assert.ok(api.includes("cache: this.shouldUseReaderRevalidationCache(path, method) ? 'no-cache' : 'no-store'"), 'client must default to no-store and selectively use no-cache');
assert.ok(api.includes("pathname === '/api/novels'"), '/api/novels must be allowlisted');
assert.ok(api.includes('/content$'), 'single content route must be allowlisted');
assert.ok(api.includes('/block-manifest$'), 'block manifest route must be allowlisted');
assert.ok(api.includes("String(method || '').toUpperCase() !== 'GET'"), 'only GET may use no-cache');
assert.ok(!api.includes("pathname.startsWith('/api/novels') return true"), 'reader cache-mode match must not be broad prefix');
console.log(JSON.stringify({ pass: PASS }));
