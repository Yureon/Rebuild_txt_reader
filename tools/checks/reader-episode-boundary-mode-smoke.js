#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const root = path.resolve(__dirname, '..', '..');
function read(rel) { return fs.readFileSync(path.join(root, rel), 'utf8'); }
const reader = read('public/scripts/rebuild/features/reader.mjs');
const chunkWindow = read('public/scripts/rebuild/features/reader/chunk-window.mjs');
const virtualLayout = read('public/scripts/rebuild/features/reader/virtual-layout.mjs');
const state = read('public/scripts/rebuild/state/app-state.mjs');
const controls = read('public/scripts/rebuild/features/settings/controls.mjs');
const elements = read('public/scripts/rebuild/features/ui/elements.mjs');
const shell = read('public/fragments/app-shell.html');
assert.ok(reader.includes('READER_EPISODE_BOUNDARY_SCROLL_BEYOND_PASS'), 'reader scroll-beyond pass marker missing');
assert.ok(reader.includes('maybeOpenNextEpisodeFromBottomOverscroll'), 'wheel bottom overscroll handler missing');
assert.ok(reader.includes('installReaderBottomTouchBoundary'), 'touch bottom overscroll handler missing');
assert.ok(reader.includes('isReaderAtEpisodeBottom(app, 2)'), 'exact bottom gate missing');
assert.ok(reader.includes("openNextEpisodeFromBoundary(app, 'bottom-overscroll-wheel')"), 'wheel bottom overscroll must open next episode');
assert.ok(!reader.includes("openNextEpisodeFromBoundary(app, 'slider-end')"), 'slider 100% must not open next episode');
assert.ok(!chunkWindow.includes('shouldAutoOpenNextEpisodeAtBottom'), 'scroll edge auto-open must remain removed');
assert.ok(!chunkWindow.includes('openNextEpisodeAtBottom'), 'chunk-window must not own episode opening');
assert.ok(!virtualLayout.includes('v356-reader-episode-bottom-anchor-pass'), 'v356 broad bottom anchor marker must stay removed');
assert.ok(virtualLayout.includes("READER_EPISODE_BOTTOM_ANCHOR_PASS = 'v360-reader-episode-bottom-anchor-pass'"), 'v360 scoped bottom anchor marker must be present');
assert.ok(virtualLayout.includes('READER_BOTTOM_PROGRESS_CLAMP_PASS'), 'bottom progress clamp marker missing');
assert.ok(virtualLayout.includes('remainingBottom <= 2'), 'bottom progress clamp must require exact bottom');
assert.ok(state.includes("? 'scrollBeyond' : 'manual'"), 'state must normalize old scroll mode to scrollBeyond only');
assert.ok(controls.includes("return 'scrollBeyond'"), 'settings controls must normalize scrollBeyond mode');
assert.ok(controls.includes('formatReaderEpisodeBoundaryMode'), 'settings status formatter missing');
assert.ok(!elements.includes('reader-episode-boundary-mode-select'), 'element collector must not keep stale boundary select');
assert.ok(elements.includes('reader-episode-boundary-manual-btn'), 'element collector missing manual boundary button');
assert.ok(elements.includes('reader-episode-boundary-auto-btn'), 'element collector missing auto boundary button');
assert.ok(!shell.includes('reader-episode-boundary-mode-select'), 'settings shell must not use boundary select');
assert.ok(shell.includes('reader-episode-boundary-manual-btn'), 'manual boundary button missing');
assert.ok(shell.includes('reader-episode-boundary-auto-btn'), 'auto boundary button missing');
assert.ok(controls.includes('readerEpisodeBoundaryManualBtn'), 'settings controls must bind manual button');
assert.ok(controls.includes('readerEpisodeBoundaryAutoBtn'), 'settings controls must bind auto button');
assert.ok(shell.includes('수동</button>'), 'manual boundary button label missing');
assert.ok(shell.includes('자동</button>'), 'auto boundary button label missing');
assert.ok(shell.includes('100% 바닥에 있을 때 한 번 더 아래로 스크롤하면 다음 화'), 'scroll-beyond description missing');
assert.ok(!shell.includes('슬라이더 100%에서 다음 화'), 'slider mode label must stay removed');
assert.ok(!shell.includes('끝까지 스크롤하면 다음 화'), 'early auto-scroll mode label must stay removed');
console.log(JSON.stringify({ pass: 'v357-reader-episode-boundary-scroll-beyond-smoke-pass' }));
